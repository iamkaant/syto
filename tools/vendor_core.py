#!/usr/bin/env python3
"""Copy the shared core into the ChimeraX bundle so it ships self-contained.

The ChimeraX bundle must not require the user to pip-install anything into
ChimeraX's Python. So `core/hitpicking` is vendored verbatim into
`chimerax/src/_vendor/hitpicking` at build time, and the bundle puts that
directory on sys.path before importing it.

Vendored, never edited: the copy is overwritten on every build, so the core
stays a single source of truth shared with the web front end.

Usage:
    python tools/vendor_core.py            # copy
    python tools/vendor_core.py --check    # verify the copy is current
"""

from __future__ import annotations

import argparse
import filecmp
import hashlib
import os
import shutil
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
SRC = os.path.join(ROOT, "core", "hitpicking")
DST = os.path.join(ROOT, "chimerax", "src", "_vendor", "hitpicking")

SKIP_DIRS = {"__pycache__", ".pytest_cache"}
SKIP_SUFFIX = (".pyc", ".pyo")


def iter_files(base):
    for dirpath, dirnames, filenames in os.walk(base):
        dirnames[:] = [d for d in dirnames if d not in SKIP_DIRS]
        for fn in filenames:
            if fn.endswith(SKIP_SUFFIX):
                continue
            full = os.path.join(dirpath, fn)
            yield full, os.path.relpath(full, base)


def digest(base):
    h = hashlib.sha256()
    for full, rel in sorted(iter_files(base), key=lambda t: t[1]):
        h.update(rel.encode())
        with open(full, "rb") as fh:
            h.update(fh.read())
    return h.hexdigest()[:16]


def vendor(check_only=False):
    if not os.path.isdir(SRC):
        sys.exit("no core package at %s" % SRC)

    handbook = os.path.join(SRC, "data", "handbook.json")
    if not os.path.exists(handbook):
        print("warning: handbook.json is not built; the bundle will ship "
              "without reference data.\n"
              "         run tools/build_data.py first.", file=sys.stderr)

    if check_only:
        if not os.path.isdir(DST):
            sys.exit("vendored copy missing; run tools/vendor_core.py")
        a, b = digest(SRC), digest(DST)
        if a != b:
            sys.exit("vendored copy is STALE (%s != %s); "
                     "run tools/vendor_core.py" % (a, b))
        print("vendored copy is current (%s)" % a)
        return a

    if os.path.isdir(DST):
        shutil.rmtree(DST)
    os.makedirs(os.path.dirname(DST), exist_ok=True)
    shutil.copytree(SRC, DST,
                    ignore=shutil.ignore_patterns(*SKIP_DIRS, "*.pyc", "*.pyo"))

    marker = os.path.join(os.path.dirname(DST), "README.txt")
    with open(marker, "w", encoding="utf-8") as fh:
        fh.write(
            "Vendored copy of core/hitpicking. DO NOT EDIT.\n"
            "Regenerated by tools/vendor_core.py on every bundle build.\n"
            "Edit the original at core/hitpicking/ instead.\n")

    n = sum(1 for _ in iter_files(DST))
    d = digest(DST)
    print("vendored %d files into %s (%s)"
          % (n, os.path.relpath(DST, ROOT), d))
    return d


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args()
    vendor(check_only=a.check)


if __name__ == "__main__":
    main()
